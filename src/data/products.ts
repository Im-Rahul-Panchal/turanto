export const products: Product[] = seeds.map(defineProduct);

/** Fast lookup tables, built once at module load. */
const productById = new Map(products.map((p) => [p.id, p]));
const productsByCategory = products.reduce<Map<string, Product[]>>((acc, product) => {
  const list = acc.get(product.categoryId);
  if (list) {
    list.push(product);
  } else {
    acc.set(product.categoryId, [product]);
  }
  return acc;
}, new Map());

export function getProduct(id: string): Product | undefined {
  return productById.get(id);
}

export function getProductsByCategory(categoryId: string): Product[] {
  return productsByCategory.get(categoryId) ?? [];
}

export function getProductName(id: string): string {
  return productById.get(id)?.name ?? 'Product';
}

/** Validates a `frequentlyBoughtWith` entry and drops unknown ids. */
export function resolveRelatedIds(ids: string[] | undefined, limit: number): Product[] {
  if (!ids) return [];
  return ids
    .map((id) => productById.get(id))
    .filter((p): p is Product => Boolean(p))
    .slice(0, limit);
}

export function getCategoryName(categoryId: string): string {
  return categories.find((c) => c.id === categoryId)?.name ?? 'Category';
}

/** Catalogue size for a category, used on category tiles and headers. */
export function getProductCount(categoryId: string): number {
  return productsByCategory.get(categoryId)?.length ?? 0;
}
