/**
 * Compact seed shape. Everything derivable — search terms, discount percentage,
 * stock status, descriptions — is filled in by `defineProduct`, which keeps this
 * catalogue readable and prevents the same fields drifting out of sync.
 */
type Seed = {
  id: string;
  name: string;
  categoryId: string;
  subcategoryId: string;
  imageKey: ImageKey;
  price: number;
  mrp: number;
  unit: string;
  rating: number;
  reviewCount?: number;
  badges?: Product['badges'];
  /** Extra search tokens beyond the product name (brand, synonym, unit). */
  keywords?: string[];
  description: string;
  highlights?: string[];
  ingredients?: string;
  nutrition?: Product['nutrition'];
  stockStatus?: Product['stockStatus'];
  unitsLeft?: number;
  frequentlyBoughtWith?: string[];
};

/** Deterministic pseudo-review count keeps badges and cards from looking empty. */
function deriveReviewCount(rating: number, seed: number): number {
  const base = Math.round((rating - 3.6) * 4200);
  return base + ((seed * 137) % 900);
}

function defineProduct(seed: Seed, index: number): Product {
  const stockStatus = seed.stockStatus ?? 'in_stock';
  const discountPercentage =
    seed.mrp > seed.price ? Math.round(((seed.mrp - seed.price) / seed.mrp) * 100) : 0;

  const searchTerms = Array.from(
    new Set([
      ...seed.name.toLowerCase().split(/[^a-z0-9]+/),
      ...(seed.keywords ?? []).map((k) => k.toLowerCase()),
    ]),
  ).filter(Boolean);

  return {
    id: seed.id,
    name: seed.name,
    searchTerms,
    categoryId: seed.categoryId,
    subcategoryId: seed.subcategoryId,
    imageKey: seed.imageKey,
    price: seed.price,
    mrp: seed.mrp,
    discountPercentage,
    unit: seed.unit,
    rating: seed.rating,
    reviewCount: seed.reviewCount ?? deriveReviewCount(seed.rating, index),
    badges: seed.badges ?? [],
    description: seed.description,
    highlights: seed.highlights ?? ['Sourced from trusted suppliers', 'Quality checked before dispatch'],
    ...(seed.ingredients !== undefined ? { ingredients: seed.ingredients } : {}),
    ...(seed.nutrition !== undefined ? { nutrition: seed.nutrition } : {}),
    stockStatus,
    ...(seed.unitsLeft !== undefined ? { unitsLeft: seed.unitsLeft } : {}),
    ...(seed.frequentlyBoughtWith !== undefined
      ? { frequentlyBoughtWith: seed.frequentlyBoughtWith }
      : {}),
  };
}

